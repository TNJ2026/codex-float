  assert.equal(popup(),null);
  await context('网页');copyFailure=true;
  await act(async()=>menuItem('复制链接地址').click());
  assert.match(popup().querySelector('[role="alert"]').textContent,/clipboard unavailable/);
  copyFailure=false;
  await act(async()=>menuItem('复制链接地址').click());
  assert.equal(popup(),null);
  await context('网页');
  await act(async()=>document.body.dispatchEvent(new dom.window.MouseEvent('pointerdown',{bubbles:true})));
  assert.equal(popup(),null);
  dom.window.HTMLElement.prototype.getBoundingClientRect=originalBounds;
  await act(async()=>root.render(React.createElement(LinkProvider,{cwd:'D:/project',scope:'thread'},React.createElement(Markdown,{text:'[网页](https://example.com)',attachments:[{src:'notes.txt',kind:'file',name:'笔记'}],references:[{ref:'source',url:'https://example.com/source',title:'来源卡片'}]}))));
