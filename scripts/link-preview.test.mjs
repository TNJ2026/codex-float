  imageViewport.getBoundingClientRect=()=>({left:0,top:0,width:400,height:300});
  Object.defineProperties(previewImage,{naturalWidth:{value:1600},naturalHeight:{value:1200}});
  await act(async()=>previewImage.dispatchEvent(new dom.window.Event('load')));
  assert.equal(document.querySelector('.image-preview-toolbar output').textContent,'25%','initial view fits both image dimensions');
  await click('原图比例');
  assert.equal(document.querySelector('.image-preview-toolbar output').textContent,'100%');
  const wheel=new dom.window.WheelEvent('wheel',{deltaY:-100,clientX:300,clientY:150,bubbles:true,cancelable:true});
  await act(async()=>imageViewport.dispatchEvent(wheel));
  assert.equal(wheel.defaultPrevented,true,'zoom must not scroll the surrounding dialog');
  assert.equal(document.querySelector('.image-preview-toolbar output').textContent,'122%');
  assert.match(previewImage.style.transform,/translate\(-22\.140/,'zoom preserves the image point under the cursor');
  const pointer=async(type,x,y,id=1)=>{
   const event=new dom.window.MouseEvent(type,{button:0,clientX:x,clientY:y,bubbles:true});
   Object.defineProperty(event,'pointerId',{value:id});
   await act(async()=>imageViewport.dispatchEvent(event));
  };
  await pointer('pointerdown',200,150);await pointer('pointermove',250,180);await pointer('pointerup',250,180);
  assert.match(previewImage.style.transform,/translate\(27\.859.*px, 30px\)/,'drag pans a zoomed image');
  await click('适应窗口');
  assert.equal(document.querySelector('.image-preview-toolbar output').textContent,'25%');
  assert.match(previewImage.style.transform,/translate\(0px, 0px\)/,'fit recenters the image');
  await act(async()=>imageViewport.dispatchEvent(new dom.window.MouseEvent('dblclick',{bubbles:true,clientX:200,clientY:150})));
  assert.equal(document.querySelector('.image-preview-toolbar output').textContent,'100%');
  await act(async()=>imageViewport.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'0',bubbles:true,cancelable:true})));
  assert.equal(document.querySelector('.image-preview-toolbar output').textContent,'25%');
  await pointer('pointerdown',100,150);await pointer('pointerdown',300,150,2);
  await pointer('pointermove',400,150,2);
  assert.equal(document.querySelector('.image-preview-toolbar output').textContent,'38%','two pointers pinch around their midpoint');
  await pointer('pointercancel',100,150);await pointer('pointerup',400,150,2);
  assert.equal(imageViewport.hasAttribute('data-dragging'),false,'cancelled gestures release drag state');
  await click('原图比例');
  await pointer('pointerdown',200,150);await pointer('pointermove',10000,10000);await pointer('pointerup',10000,10000);
  assert.match(previewImage.style.transform,/translate\(600px, 450px\)/,'panning stops at image edges');
  await click('关闭');
  await click('文本');
  assert.deepEqual(calls[1],{cmd:'read_file_preview',args:{path:'D:/project/README.md'}});
  assert.equal(document.querySelector('dialog pre').textContent,'<script>alert(1)</script>\n中文文本');
  assert.equal(document.querySelector('dialog script'),null);
  await click('关闭');
  await click('代码');
  assert.ok(document.querySelector('dialog .language-typescript .hljs-keyword'));
  assert.equal(document.querySelector('dialog code').textContent,'const message: string = "<img src=x onerror=alert(1)>";');
  assert.equal(document.querySelector('dialog img,dialog [onerror]'),null);
  await click('关闭');
  await click('其他文件');
  assert.deepEqual(calls.slice(-2),[{cmd:'read_file_preview',args:{path:'D:/report.pdf'}},{cmd:'reveal_file',args:{path:'D:/report.pdf'}}]);
  assert.equal(document.querySelector('dialog'),null);
  await click('慢文件');
  assert.match(document.querySelector('dialog').textContent,/正在读取/);
  await click('关闭');
  const callsBeforeLateResponse=calls.length;
  await act(async()=>finishRead({kind:'folder'}));
  assert.equal(document.querySelector('dialog'),null);
  assert.equal(calls.length,callsBeforeLateResponse);
  const before=calls.length;
  await click('危险');
  assert.match(document.querySelector('[role="alert"]').textContent,/不支持/);
  assert.equal(calls.length,before);
  await act(async()=>document.querySelector('dialog').dispatchEvent(new dom.window.Event('cancel',{cancelable:true})));
  assert.equal(document.querySelector('dialog'),null);
  const popup=()=>document.querySelector('[role="menu"]');
  const menuItem=label=>[...popup().querySelectorAll('button')].find(button=>button.textContent===label);
  const context=async label=>{
   const anchor=[...document.querySelectorAll('a')].find(element=>element.textContent===label);
   const event=new dom.window.MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:1000,clientY:740,button:2});
   await act(async()=>anchor.dispatchEvent(event));
   assert.equal(event.defaultPrevented,true);
   return anchor;
  };
  const originalBounds=dom.window.HTMLElement.prototype.getBoundingClientRect;
  dom.window.HTMLElement.prototype.getBoundingClientRect=function(){return this.classList.contains('link-context-menu')?{width:220,height:120}:originalBounds.call(this);};
  const beforeContext=calls.length;
  const webAnchor=await context('网页');
  assert.equal(menuItem('使用默认 App 打开'),undefined);
  assert.equal(calls.length,beforeContext,'right-clicking must not open a link');
  assert.equal(popup().style.left,'796px');
  assert.equal(popup().style.top,'640px');
  await act(async()=>document.activeElement.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'ArrowDown',bubbles:true})));
  assert.ok(document.activeElement===menuItem('复制链接地址'),'ArrowDown focuses the copy action');
  await act(async()=>document.activeElement.click());
  assert.deepEqual(calls.at(-1),{cmd:'copy_text',args:{text:'https://example.com/a.png'}});
  assert.equal(popup(),null);
  assert.ok(document.activeElement===webAnchor,'closing the menu restores link focus');
  await context('文本');
  openFailure=true;
  await act(async()=>menuItem('使用默认 App 打开').click());
  assert.match(popup().querySelector('[role="alert"]').textContent,/No default app/);
  openFailure=false;
  await act(async()=>menuItem('使用默认 App 打开').click());
  assert.deepEqual(calls.at(-1),{cmd:'open_file',args:{path:'D:/project/README.md'}});
  await context('图片');
  await act(async()=>menuItem('使用默认 App 打开').click());
  assert.deepEqual(calls.at(-1),{cmd:'open_file',args:{path:'D:/a.png'}});
  await context('文本');
  await act(async()=>menuItem('复制文件路径').click());
  assert.deepEqual(calls.at(-1),{cmd:'copy_text',args:{text:'D:/project/README.md'}});
  await context('文本');
  await act(async()=>menuItem('在文件夹中查看').click());
  assert.deepEqual(calls.at(-1),{cmd:'reveal_file',args:{path:'D:/project/README.md'}});
  await context('网页');
  await act(async()=>menuItem('打开链接').click());
